"""Generated duration limits: the reference bisection, the archive listing and their copies in CONTRIBUTING.md."""
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("tunes_duration", ROOT / "tools/duration_table.py")
durations = importlib.util.module_from_spec(spec)
spec.loader.exec_module(durations)
checker = durations.checker

CHANNELS = {"off": 1, "stereo": 2, "binaural": 2, "amb1": 4, "amb3": 16}
OVERHEAD = 4_000_000
FAKE_HARNESS = '''#!/usr/bin/env python3
import sys
if sys.argv[1:] == ["--engine"]:
    if "fail" in sys.argv[0]:
        sys.stderr.write("engine table missing\\nsecond line\\n")
        sys.exit(3)
    print("ENGINE a1 fake")
    sys.exit(0)
print("ENGINE a1 fake")
print("INSPECT fs=48000 frames=1440000 channels=2 length_ns=30000000000 pcm_bytes=5760000 "
      "render_bytes_lower_bound=15520000 hash_present=0")
'''


def fake_row(harness, record):
    """An in-process renderer whose memory lower bound is a fixed overhead plus two PCM buffers."""
    header = dict(line.split(" ", 1) for line in record.read_text().splitlines()[:5])
    fs, length = int(header["fs"]), int(header["length_ns"])
    channels = CHANNELS[header["space"]]
    frames = length * fs // 10**9
    pcm = frames * channels * 2
    return {"fs": str(fs), "frames": str(frames), "channels": str(channels), "length_ns": str(length),
            "pcm_bytes": str(pcm), "render_bytes_lower_bound": str(OVERHEAD + 2 * pcm)}


def expected_cell(fs, channels):
    """Closed form for fake_row: OVERHEAD + 5 PCM buffers must fit, so frames <= (budget - OVERHEAD) // (10 x channels)."""
    frames = (checker.MAX_MEMORY_BYTES - OVERHEAD) // (5 * channels * 2)
    milliseconds = min(300_000, -(-1000 * (frames + 1) // fs) - 1)
    return "%.3f s (%s)" % (milliseconds / 1000, "duration rule" if milliseconds == 300_000 else "memory budget")


def documented():
    """Return the generated table and archive summary that CONTRIBUTING.md shows between their markers."""
    text = (ROOT / "CONTRIBUTING.md").read_text(encoding="utf-8")
    blocks = []
    for name in ("duration-table", "archive-exceptions"):
        found = re.findall(r"^<!-- %s: generated by tools/duration_table\.py --harness \"\$TRUSTED_HARNESS\"[^\n]*-->\n"
                           r"(.*?)^<!-- end %s -->$" % (name, name), text, re.S | re.M)
        assert len(found) == 1, name
        blocks.append(found[0])
    return blocks


class DurationTableTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix="tunes-duration-test-")
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)

    def harness(self, name="harness"):
        path = self.root / name
        path.write_text(FAKE_HARNESS)
        path.chmod(0o755)
        return path

    def test_table_bisects_the_longest_admissible_reference_per_space_and_rate(self):
        with patch.object(durations, "inspect", side_effect=fake_row) as inspected:
            table = durations.table(self.harness())
        rows = ["| Space | Channels | 44100 Hz | 48000 Hz |", "| --- | ---: | ---: | ---: |"]
        rows += ["| `%s` | %d | %s |" % (space, channels, " | ".join(expected_cell(fs, channels) for fs in (44100, 48000)))
                 for space, channels in CHANNELS.items()]
        self.assertEqual(table, "\n".join(rows) + "\n")
        self.assertIn("| `stereo` | 2 | 299.813 s (memory budget) | 275.453 s (memory budget) |", table)
        self.assertIn("| `off` | 1 | 300.000 s (duration rule) | 300.000 s (duration rule) |", table)
        drafts = [call.args[1] for call in inspected.call_args_list]
        self.assertTrue(all(path.name == "reference.tl" for path in drafts))
        self.assertLess(len(drafts), 10 * 21)

    def test_reference_draft_keeps_one_voice_and_releases_before_the_end(self):
        draft = durations.reference("a1 fake", 44100, "amb1", 123_456)
        self.assertTrue(draft.startswith("timeline draft2\nengine a1 fake\nfs 44100\nlength_ns 123456000000\nspace amb1\n"))
        self.assertTrue(draft.endswith("\n121456000000 melody 0 off\n"))
        self.assertEqual(draft.count("\nvoice "), 1)

    def test_inspection_uses_the_checker_native_limits(self):
        record = self.root / "draft.tl"
        record.write_text("timeline draft2\n")
        with patch.object(checker, "run", wraps=checker.run) as run:
            info = durations.inspect(self.harness(), record)
        self.assertEqual(info["render_bytes_lower_bound"], "15520000")
        self.assertIsNone(durations.refusal(info))
        options = run.call_args.kwargs
        self.assertEqual((options["name"], options["timeout"], options["cpu_seconds"], options["memory_bytes"],
                          options["cwd"]), ("Native inspection", checker.NATIVE_TIMEOUT, 120,
                                            checker.MAX_MEMORY_BYTES, self.root))

    def test_refusals_map_to_the_first_admission_rule_and_unknown_errors_propagate(self):
        base = {"fs": "48000", "frames": "1440000", "channels": "2", "length_ns": "30000000000",
                "pcm_bytes": "5760000", "render_bytes_lower_bound": "15520000"}
        cases = [({"fs": "32000"}, "sample rate"), ({"frames": "960000", "length_ns": "20000000000"}, "duration"),
                 ({"pcm_bytes": "1"}, "PCM size"), ({"render_bytes_lower_bound": str(checker.MAX_RENDER_BYTES + 1)},
                                                    "memory budget"), ({"fs": "32000", "frames": "1"}, "sample rate")]
        for change, rule in cases:
            with self.subTest(change=change):
                self.assertEqual(durations.refusal(dict(base, **change)), rule)
        with self.assertRaises(ValueError):
            durations.refusal(dict(base, channels="two"))

    def test_archive_counts_each_refused_version_once_with_its_rule_and_values(self):
        rows = {"a.tl": {"fs": "32000", "frames": "960000"}, "b.tl": {"frames": "480000", "length_ns": "10000000000"},
                "c.tl": {"render_bytes_lower_bound": str(checker.MAX_MEMORY_BYTES)}, "d.tl": {},
                "e.tl": {"frames": "14400048", "length_ns": "300001000000"}}
        base = {"fs": "48000", "frames": "1440000", "channels": "2", "length_ns": "30000000000",
                "pcm_bytes": "5760000", "render_bytes_lower_bound": "15520000"}

        def row(harness, record):
            info = dict(base, **rows[record.name])
            info["pcm_bytes"] = str(int(info["frames"]) * 2 * 2)
            return info

        songs = [{"variants": [{"id": "song-" + name[0], "paths": ["records/" + name]}]} for name in sorted(rows)]
        (self.root / "library.json").write_text(json.dumps({"songs": songs}))
        with patch.object(checker.catalog, "validate") as validate, patch.object(durations, "inspect", side_effect=row):
            listing = durations.archive(self.harness(), self.root)
            validate.assert_called_once_with(self.root)
            self.assertEqual(listing, "4 retained versions fall outside the current admission rules: 1 on sample rate, "
                             "2 on duration and 1 on the memory budget.\n"
                             "- `song-a`: sample rate (32000 Hz, 30.000 s, 2 channels)\n"
                             "- `song-b`: duration (48000 Hz, 10.000 s, 2 channels)\n"
                             "- `song-c`: memory budget (48000 Hz, 30.000 s, 2 channels)\n"
                             "- `song-e`: duration (48000 Hz, 300.001 s, 2 channels)\n")
            del rows["a.tl"], rows["b.tl"], rows["e.tl"]
            (self.root / "library.json").write_text(json.dumps({"songs": songs[2:4]}))
            self.assertEqual(durations.archive(self.harness(), self.root).splitlines()[0],
                             "1 retained version falls outside the current admission rules: 1 on the memory budget.")
            (self.root / "library.json").write_text(json.dumps({"songs": songs[3:4]}))
            self.assertEqual(durations.archive(self.harness(), self.root),
                             "0 retained versions fall outside the current admission rules.\n")

    def test_failed_engine_query_exits_with_the_command_status_and_first_error_line(self):
        errors = io.StringIO()
        with patch.object(sys, "argv", ["duration_table.py", "--harness", str(self.harness("fail-harness"))]), \
                contextlib.redirect_stderr(errors), self.assertRaises(SystemExit) as stopped:
            durations.main()
        self.assertEqual(stopped.exception.code, 1)
        self.assertEqual(errors.getvalue(),
                         'Duration table failed: Native engine query failed (exit status 3): "engine table missing".\n')

    def test_contributing_shows_the_generated_table_and_archive_summary(self):
        table, summary = documented()
        lines = table.splitlines()
        self.assertEqual(lines[:2], ["| Space | Channels | 44100 Hz | 48000 Hz |", "| --- | ---: | ---: | ---: |"])
        cell = r"\d{1,3}\.\d{3} s \((?:duration rule|memory budget)\)"
        self.assertEqual(len(lines), 2 + len(durations.SPACES))
        for line, space in zip(lines[2:], durations.SPACES):
            self.assertRegex(line, r"\A\| `%s` \| \d+ \| %s \| %s \|\Z" % (space, cell, cell))
        self.assertEqual(lines[2], "| `off` | 1 | 300.000 s (duration rule) | 300.000 s (duration rule) |")
        self.assertRegex(summary, r"\A\d+ retained versions? falls? outside the current admission rules(?:: [^\n]+)?\.\n\Z")
        text = (ROOT / "CONTRIBUTING.md").read_text(encoding="utf-8")
        self.assertLess(text.index("<!-- end archive-exceptions -->"), text.index("## Metadata and declarations"))
        self.assertIn("### Retained archive exceptions", text)
        self.assertIn("Retained archive exceptions in CONTRIBUTING.md", checker.ARCHIVE_NOTE)

    @unittest.skipUnless(os.environ.get("JOTTUNE_PR_HARNESS"), "Set JOTTUNE_PR_HARNESS for the real native boundary.")
    def test_documented_limits_match_the_trusted_renderer(self):
        harness = Path(os.environ["JOTTUNE_PR_HARNESS"]).resolve()
        table, summary = documented()
        self.assertEqual(table, durations.table(harness))
        self.assertEqual(summary, durations.archive(harness, ROOT).splitlines(keepends=True)[0])


if __name__ == "__main__":
    unittest.main()
